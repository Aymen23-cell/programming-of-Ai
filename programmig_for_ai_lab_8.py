"""
AI Data Explorer: Air Quality (PM2.5) Monitoring for Lahore
============================================================
Problem : Lahore suffers from severe smog every winter. A local organization
          wants to find out WHEN and WHERE air quality is dangerous, and which
          weather conditions make it worse, so that alerts can be issued early.
Method  : 1) Load / create data  2) NumPy statistics  3) Pandas cleaning+analysis
          4) Rule-based decisions  5) Report + saved files  6) Simple ML model

NOTE: The dataset is SIMULATED (realistic patterns, but not official readings).
      If you have a real CSV, put it in "air_quality_raw.csv" with the same
      columns and the script will load it instead of generating one.
"""

import os
import numpy as np
import pandas as pd

RAW_FILE = "air_quality_raw.csv"
CLEAN_FILE = "air_quality_cleaned.csv"
REPORT_FILE = "final_report.txt"


# ----------------------------------------------------------------------
# STEP 1: DATA HANDLING  (lists, dictionaries, loops, functions, files)
# ----------------------------------------------------------------------
def create_dataset():
    """Create a realistic (simulated) dataset using lists, dicts and loops."""
    rng = np.random.default_rng(42)  # fixed seed -> same data every run

    # dictionary: station -> typical pollution level (traffic/industry effect)
    stations = {
        "Gulberg": 105, "Johar Town": 95, "DHA": 80,
        "Shahdara": 135, "Model Town": 90, "Ravi Road": 150,
    }
    dates = pd.date_range("2025-10-01", "2025-12-31", freq="D")

    rows = []
    for station, base in stations.items():          # loop 1: stations
        for date in dates:                          # loop 2: days
            month = date.month
            # smog gets worse in Nov, a bit in Dec, mild in Oct
            season = {10: 0.8, 11: 1.5, 12: 1.2}[month]
            temp = rng.normal({10: 27, 11: 20, 12: 14}[month], 3)
            humidity = np.clip(rng.normal(60, 15), 20, 98)
            wind = np.clip(rng.normal(9, 4), 0.5, 25)
            pm25 = (base * season
                    + 0.8 * (humidity - 60)       # humid air traps smog
                    - 4.0 * (wind - 9)             # wind clears smog
                    + rng.normal(0, 18))
            pm25 = max(pm25, 5)
            pm10 = pm25 * rng.uniform(1.4, 1.9)
            rows.append([date.strftime("%Y-%m-%d"), station, round(pm25, 1),
                         round(pm10, 1), round(temp, 1), round(humidity, 1),
                         round(wind, 1)])

    df = pd.DataFrame(rows, columns=["date", "station", "pm25", "pm10",
                                     "temperature", "humidity", "wind_speed"])

    # --- make the data "dirty" on purpose, like real sensor data ---
    n = len(df)
    for col in ["pm25", "pm10", "humidity", "wind_speed"]:
        idx = rng.choice(n, size=int(0.03 * n), replace=False)
        df.loc[idx, col] = np.nan                                  # missing values
    bad = rng.choice(n, size=6, replace=False)
    df.loc[bad[:3], "pm25"] = -99                                  # sensor error
    df.loc[bad[3:], "pm25"] = 999                                  # sensor error
    dupes = df.sample(15, random_state=1)
    df = pd.concat([df, dupes], ignore_index=True)                 # duplicates
    return df.sample(frac=1, random_state=7).reset_index(drop=True)


def load_data():
    """File handling: load the CSV if it exists, otherwise create and save it."""
    if os.path.exists(RAW_FILE):
        print(f"Loading existing file: {RAW_FILE}")
        return pd.read_csv(RAW_FILE)
    print("No dataset found -> creating one and saving it.")
    df = create_dataset()
    df.to_csv(RAW_FILE, index=False)
    return df


# ----------------------------------------------------------------------
# STEP 2: PANDAS - inspect and clean
# ----------------------------------------------------------------------
def clean_data(df):
    log = {}
    log["rows_before"] = len(df)
    log["missing_before"] = int(df.isna().sum().sum())

    df = df.drop_duplicates()
    log["duplicates_removed"] = log["rows_before"] - len(df)

    # sensor errors: PM2.5 must be between 0 and 800 -> else treat as missing
    invalid = (df["pm25"] < 0) | (df["pm25"] > 800)
    log["invalid_pm25_fixed"] = int(invalid.sum())
    df.loc[invalid, "pm25"] = np.nan

    # fill missing numbers with the MEDIAN of the same station
    num_cols = ["pm25", "pm10", "temperature", "humidity", "wind_speed"]
    for col in num_cols:
        df[col] = df.groupby("station")[col].transform(lambda s: s.fillna(s.median()))

    df["date"] = pd.to_datetime(df["date"])
    df["month"] = df["date"].dt.month_name()
    df = df.sort_values(["station", "date"]).reset_index(drop=True)

    log["rows_after"] = len(df)
    log["missing_after"] = int(df.isna().sum().sum())
    return df, log


# ----------------------------------------------------------------------
# STEP 3: NUMPY - statistics, indexing, slicing, vectorized operations
# ----------------------------------------------------------------------
def numpy_statistics(df):
    pm = df["pm25"].to_numpy()              # DataFrame column -> NumPy array
    stats = {
        "mean": np.mean(pm), "median": np.median(pm), "std": np.std(pm),
        "min": np.min(pm), "max": np.max(pm),
        "90th percentile": np.percentile(pm, 90),
    }
    first_week = pm[:7]                     # slicing
    worst_index = int(np.argmax(pm))        # indexing
    # vectorized: 7-day moving average without any loop
    moving_avg = np.convolve(pm, np.ones(7) / 7, mode="valid")
    # vectorized: z-score for every record at once
    z = (pm - pm.mean()) / pm.std()
    # vectorized: AQI category using np.select (like many if/elif at once)
    bins = [pm <= 12, pm <= 35.4, pm <= 55.4, pm <= 150.4, pm <= 250.4]
    names = ["Good", "Moderate", "Unhealthy (Sensitive)", "Unhealthy", "Very Unhealthy"]
    category = np.select(bins, names, default="Hazardous")
    return stats, first_week, worst_index, moving_avg, z, category


# ----------------------------------------------------------------------
# STEP 4: DECISION RULES (conditions + functions)
# ----------------------------------------------------------------------
def smog_alert(row):
    """Rule 2: dangerous combination = high PM2.5 + low wind + high humidity."""
    if row["pm25"] > 150 and row["wind_speed"] < 8 and row["humidity"] > 60:
        return "ALERT: close schools, wear masks"
    elif row["pm25"] > 150:
        return "WARNING: limit outdoor activity"
    return "OK"


def apply_rules(df):
    # Rule 1: classify each day (done with NumPy above)
    # Rule 2: smog alert (function above)
    df["alert"] = df.apply(smog_alert, axis=1)
    # Rule 3: unusual record = PM2.5 more than 2.5 std-devs above its own station mean
    g = df.groupby("station")["pm25"]
    df["station_z"] = (df["pm25"] - g.transform("mean")) / g.transform("std")
    df["unusual_spike"] = df["station_z"] > 2.5
    return df


# ----------------------------------------------------------------------
# STEP 5: SIMPLE ML EXTENSION - linear regression with NumPy only
# ----------------------------------------------------------------------
def train_model(df):
    X = pd.get_dummies(df[["temperature", "humidity", "wind_speed", "station"]],
                       columns=["station"], dtype=float)
    X.insert(0, "bias", 1.0)
    y = df["pm25"].to_numpy()
    Xv = X.to_numpy()

    rng = np.random.default_rng(0)
    idx = rng.permutation(len(df))
    cut = int(0.8 * len(df))
    tr, te = idx[:cut], idx[cut:]

    w, *_ = np.linalg.lstsq(Xv[tr], y[tr], rcond=None)   # least squares
    pred = Xv[te] @ w
    mae = np.mean(np.abs(pred - y[te]))
    ss_res = np.sum((y[te] - pred) ** 2)
    ss_tot = np.sum((y[te] - y[te].mean()) ** 2)
    r2 = 1 - ss_res / ss_tot
    coefs = dict(zip(X.columns, w))
    return mae, r2, coefs


