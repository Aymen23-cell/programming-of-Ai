# MAIN PROGRAM
# ----------------------------------------------------------------------
def main():
    raw = load_data()
    print("\n--- Raw data structure ---")
    print(raw.shape)
    print(raw.dtypes)
    print("Missing values per column:\n", raw.isna().sum())

    df, log = clean_data(raw)
    stats, first_week, worst_idx, moving_avg, z, category = numpy_statistics(df)
    df["category"] = category
    df = apply_rules(df)
    df.to_csv(CLEAN_FILE, index=False)

    # ----- Pandas analysis -----
    by_station = df.groupby("station")["pm25"].agg(["mean", "max"]).round(1).sort_values("mean", ascending=False)
    month_order = ["October", "November", "December"]
    by_month = df.groupby("month")["pm25"].mean().reindex(month_order).round(1)
    unhealthy_days = df[df["pm25"] > 55.4].groupby("station").size().sort_values(ascending=False)
    corr = df[["pm25", "temperature", "humidity", "wind_speed"]].corr()["pm25"].round(2)
    alerts = df["alert"].value_counts()
    spikes = df[df["unusual_spike"]].sort_values("pm25", ascending=False).head(5)[
        ["date", "station", "pm25"]]
    worst_station = by_station.index[0]
    best_station = by_station.index[-1]
    worst_month = by_month.idxmax()

    mae, r2, coefs = train_model(df)

    # ----- Report -----
    L = []
    L.append("=" * 62)
    L.append("   AI DATA EXPLORER - LAHORE AIR QUALITY REPORT")
    L.append("=" * 62)
    L.append("\n1. DATA CLEANING")
    L.append(f"   Rows before/after      : {log['rows_before']} -> {log['rows_after']}")
    L.append(f"   Duplicates removed     : {log['duplicates_removed']}")
    L.append(f"   Invalid PM2.5 fixed    : {log['invalid_pm25_fixed']}")
    L.append(f"   Missing values         : {log['missing_before']} -> {log['missing_after']}")
    L.append("\n2. KEY STATISTICS OF PM2.5 (NumPy, ug/m3)")
    for k, v in stats.items():
        L.append(f"   {k:<16}: {v:.1f}")
    L.append("\n3. AVERAGE PM2.5 BY STATION")
    L.append(by_station.to_string())
    L.append("\n4. AVERAGE PM2.5 BY MONTH")
    L.append(by_month.to_string())
    L.append("\n5. DAYS ABOVE 55.4 (UNHEALTHY) PER STATION")
    L.append(unhealthy_days.to_string())
    L.append("\n6. CORRELATION WITH PM2.5")
    L.append(corr.to_string())
    L.append("\n7. ALERTS GENERATED BY RULES")
    L.append(alerts.to_string())
    L.append("\n8. TOP 5 UNUSUAL SPIKES (z > 2.5 within station)")
    L.append(spikes.to_string(index=False))
    L.append("\n9. DATA-DRIVEN INSIGHTS")
    L.append(f"   Insight 1: {worst_station} has the worst air (avg {by_station.loc[worst_station,'mean']}), "
             f"{best_station} the best (avg {by_station.loc[best_station,'mean']}).")
    L.append(f"   Insight 2: {worst_month} is the worst month (avg {by_month.max()}); smog peaks in winter.")
    L.append(f"   Insight 3: Wind speed is negatively related to PM2.5 (r={corr['wind_speed']}) and "
             f"humidity positively (r={corr['humidity']}).")
    L.append(f"   Insight 4: Only {int(alerts.get('ALERT: close schools, wear masks', 0))} days met the "
             f"full smog-ALERT condition (PM2.5>150, low wind, high humidity).")
    L.append("\n10. RECOMMENDATIONS")
    L.append(f"   - Install extra monitors and traffic controls near {worst_station}.")
    L.append(f"   - Issue public warnings in {worst_month}, when wind is low and humidity high.")
    L.append("   - Use the ALERT rule (PM2.5>150, wind<8, humidity>60) to trigger school/mask advisories.")
    L.append("\n11. AI EXTENSION (Linear Regression, NumPy)")
    L.append(f"   Test MAE = {mae:.1f} ug/m3, R2 = {r2:.2f}")
    L.append(f"   Wind coefficient = {coefs['wind_speed']:.2f}, humidity coefficient = {coefs['humidity']:.2f}")
    L.append("   Future use: train a model (Random Forest / LSTM) on daily weather + station data")
    L.append("   to forecast PM2.5 for the NEXT day, so alerts go out before smog arrives.")
    L.append("   Needs more real data (full years, traffic counts, crop-burning data).")
    text = "\n".join(L)
    print("\n" + text)
    with open(REPORT_FILE, "w") as f:   # file handling
        f.write(text)

    print(f"\nSaved: {RAW_FILE}, {CLEAN_FILE}, {REPORT_FILE}")
    print("NumPy demo -> first 7 days:", first_week, "| worst-day index:", worst_idx,
          "| moving-average length:", len(moving_avg))


if __name__ == "__main__":
    main()

